#ifndef SOC_ZHIHE_A210_NCORE_H
#define SOC_ZHIHE_A210_NCORE_H

#include <soc/addressmap.h>

#define NCORE_PORT_STRIDE 0x1000
#define NCORE_ADDRESS_MAP_MODE 0x3c0
#define NCORE_INTERLEAVE 0x3c4
#define NCORE_MAP_DUAL_CHANNEL 1
#define NCORE_INTERLEAVE_256 1
#define NCORE_REGION_STRIDE 16
#define NCORE_REGION_CONTROL(n) (0x400 + (n) * NCORE_REGION_STRIDE)
#define NCORE_REGION_BASE_LOW(n) (0x404 + (n) * NCORE_REGION_STRIDE)
#define NCORE_REGION_BASE_HIGH(n) (0x408 + (n) * NCORE_REGION_STRIDE)
#define NCORE_REGION_ENABLE_LOCAL 0x80000040
#define NCORE_REGION_SIZE_SHIFT 20
#define NCORE_REGION_IO_512M 0xc1100040
#define NCORE_REGION_IO_256M 0xc1000040
#define NCORE_REGION_OCRAM 0x80800040
#define NCORE_REGION_IO_32G 0xc1700040
#define NCORE_REGION_IO_LOW_BASE 0x00040000
#define NCORE_REGION_IO_HIGH_BASE 0x00060000
#define NCORE_REGION_OCRAM_BASE (A210_OCRAM_BASE >> 12)
#define NCORE_REGION_REMOTE_BASE 0x01800000
#define NCORE_PORT_ACCESS0 0x100
#define NCORE_PORT_ACCESS1 0x140
#define NCORE_PORT_DVM_ACCESS 0x118
#define NCORE_PORT_ACCESS_ALL 31
#define NCORE_PORT_ENABLE 1
#define NCORE_SNOOP_FILTER0 0xc00
#define NCORE_SNOOP_FILTER1 0xc04
#define NCORE_SNOOP_FILTER2 0xc08
#define NCORE_CPU_SNOOP_FILTER 0xf0f0f0
#define NCORE_ALL_SNOOP_FILTER 0xffffff
#define NCORE_XAIUTCR 0x40
#define NCORE_XAIUTAR 0x44
#define NCORE_ATTACH_REQUEST (1U << 9)
#define NCORE_ATTACH_ACK (1U << 5)

#define SYSREG_DFMU_CONFIG (A210_SYSREG_BASE + 0x14)
#define DFMU_DDR_WIDTH_INTERLEAVE_MASK 3
#define DFMU_DDR_DUAL_256 (1U << 1)

#endif
