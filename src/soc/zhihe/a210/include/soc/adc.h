#ifndef SOC_ZHIHE_A210_ADC_H
#define SOC_ZHIHE_A210_ADC_H

#define ADC_PHY_CONFIG 0x00
#define ADC_PHY_CONTROL 0x04
#define ADC_OPERATION_CONTROL 0x0c
#define ADC_SINGLE_START 0x10
#define ADC_CLOCK_CONTROL 0x14
#define ADC_START_TIME 0x18
#define ADC_SAMPLE_TIME 0x1c
#define ADC_SAMPLE_DATA 0x20
#define ADC_ACTUAL_INTERRUPT_MASK 0x50
#define ADC_DELTA_INTERRUPT_MASK 0x54
#define ADC_PHY_ENABLE (1U << 0)
#define ADC_PHY_RESET (1U << 4)
#define ADC_SINGLE_MODE (1U << 0)
#define ADC_CHANNEL_ENABLE(ch) (1U << (12 + (ch)))
#define ADC_SAMPLE_VALID (1U << 15)
#define ADC_SAMPLE_MASK 0xfff
#define ADC_PHY_REFERENCE_CONFIG 3
#define ADC_CLOCK_DEFAULT 0x10004
#define ADC_START_CYCLES 0x160
#define ADC_SAMPLE_CYCLES 14
#define ADC_USED_INTERRUPT_MASK 0xf
#define ADC_CHANNEL_COUNT 8
#define ADC_AVERAGE_SAMPLES 16
#define ADC_REFERENCE_MV 1800
#define ADC_RESOLUTION 4096

#endif
